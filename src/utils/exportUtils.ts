// Request write permissions for Android external storage (legacy devices)
const ensureAndroidDownloadPermission = async (): Promise<void> => {
    if (Platform.OS !== 'android') return;
    try {
        const perms: string[] = [];
        if (PermissionsAndroid.PERMISSIONS.WRITE_EXTERNAL_STORAGE) {
            perms.push(PermissionsAndroid.PERMISSIONS.WRITE_EXTERNAL_STORAGE);
        }
        if (PermissionsAndroid.PERMISSIONS.READ_EXTERNAL_STORAGE) {
            perms.push(PermissionsAndroid.PERMISSIONS.READ_EXTERNAL_STORAGE);
        }
        if (perms.length === 0) return;
        const res = await PermissionsAndroid.requestMultiple(perms as any);
        const denied = Object.values(res).some((v) => v !== PermissionsAndroid.RESULTS.GRANTED);
        if (denied) {
            throw new Error('Storage permission denied');
        }
    } catch (e) {
        // If request API not available, proceed and let write fail if not permitted
    }
};

